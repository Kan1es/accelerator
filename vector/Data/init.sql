CREATE TABLE department (
  id SERIAL PRIMARY KEY, name VARCHAR(255), parent_id INT REFERENCES department(id)
);

CREATE TABLE role (
  id SERIAL PRIMARY KEY, name VARCHAR(255), power INT
);

CREATE TABLE employee (
  id SERIAL PRIMARY KEY, name VARCHAR(255), role_id INT REFERENCES role(id), department_id INT REFERENCES department(id), is_active BOOLEAN DEFAULT TRUE
);

CREATE TABLE category (
  id SERIAL PRIMARY KEY, name VARCHAR(255), keywords TEXT, parent_id INT REFERENCES category(id)
);

CREATE TABLE escalation_rule (
  id SERIAL PRIMARY KEY, category_id INT REFERENCES category(id), time_limit INT
);

CREATE TABLE ticket (
  id SERIAL PRIMARY KEY, description TEXT, category_id INT REFERENCES category(id), priority INT, status VARCHAR(50), created_at TIMESTAMP, creator_id INT REFERENCES employee(id), assignee_id INT REFERENCES employee(id)
);

CREATE TABLE ticket_assignment (
  id SERIAL PRIMARY KEY, ticket_id INT REFERENCES ticket(id), assignee_id INT REFERENCES employee(id), assigner_id INT REFERENCES employee(id), assigned_time TIMESTAMP, resolved_time TIMESTAMP, is_resolved BOOLEAN DEFAULT FALSE
);

